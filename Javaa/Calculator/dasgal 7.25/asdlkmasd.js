/* ============================================================
   📖 ЖИШЭЭ (map, filter, find юу хийдгийг эхлээд ойлгоцгооё)
   ============================================================ */

const example = [1, 2, 3, 4, 5];

// map - массив бүрийн элемент дээр ажиллаад, ШИНЭ массив буцаана
// (хэдэн ширхэг орж байсан бол яг тэр хэдэн ширхэг гарна)
const mapExample = example.map(function (n) {
  return n * 10;
});
console.log(mapExample); // [10, 20, 30, 40, 50]

// filter - шалгуурт таарсан элементүүдийг л шүүж, ШИНЭ массив буцаана
// (орсноос цөөн эсвэл тэнцүү ширхэг гарна)
const filterExample = example.filter(function (n) {
  return n > 2;
});
console.log(filterExample); // [3, 4, 5]

// find - шалгуурт таарсан ЭХНИЙ элементийг л буцаана (массив биш ганц утга)
const findExample = example.find(function (n) {
  return n > 2;
});
console.log(findExample); // 3

